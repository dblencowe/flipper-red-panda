"""A small pixel font for the text some firmware pictures carry.

Drawn for this project: capitals 7 px high, x-height 5, descenders 2,
one pixel between letters. Only the characters the pictures need.
"""

# Each glyph: 9 rows (0-6 cap height, 7-8 descender), '#' is ink.
_RAW = {
    "A": [".###.", "#...#", "#...#", "#####", "#...#", "#...#", "#...#"],
    "D": ["####.", "#...#", "#...#", "#...#", "#...#", "#...#", "####."],
    "E": ["####", "#...", "#...", "###.", "#...", "#...", "####"],
    "H": ["#...#", "#...#", "#...#", "#####", "#...#", "#...#", "#...#"],
    "I": ["#", "#", "#", "#", "#", "#", "#"],
    "K": ["#...#", "#..#.", "#.#..", "##...", "#.#..", "#..#.", "#...#"],
    "L": ["#...", "#...", "#...", "#...", "#...", "#...", "####"],
    "N": ["#...#", "##..#", "#.#.#", "#.#.#", "#..##", "#...#", "#...#"],
    "O": [".###.", "#...#", "#...#", "#...#", "#...#", "#...#", ".###."],
    "P": ["####.", "#...#", "#...#", "####.", "#....", "#....", "#...."],
    "R": ["####.", "#...#", "#...#", "####.", "#.#..", "#..#.", "#...#"],
    "S": [".####", "#....", "#....", ".###.", "....#", "....#", "####."],
    "V": ["#...#", "#...#", "#...#", ".#.#.", ".#.#.", ".#.#.", "..#.."],
    "W": ["#...#", "#...#", "#...#", "#.#.#", "#.#.#", "##.##", "#...#"],
    "a": ["....", "....", ".##.", "...#", ".###", "#..#", ".###"],
    "d": ["...#", "...#", ".###", "#..#", "#..#", "#..#", ".###"],
    "e": ["....", "....", ".##.", "#..#", "####", "#...", ".##."],
    "g": ["....", "....", ".###", "#..#", "#..#", "#..#", ".###", "...#", ".##."],
    "h": ["#...", "#...", "###.", "#..#", "#..#", "#..#", "#..#"],
    "i": ["#", ".", "#", "#", "#", "#", "#"],
    "l": ["#", "#", "#", "#", "#", "#", "#"],
    "n": ["....", "....", "###.", "#..#", "#..#", "#..#", "#..#"],
    "o": ["....", "....", ".##.", "#..#", "#..#", "#..#", ".##."],
    "r": ["...", "...", "#.#", "##.", "#..", "#..", "#.."],
    "s": ["....", "....", ".###", "#...", ".##.", "...#", "###."],
    "t": [".#.", ".#.", "###", ".#.", ".#.", ".#.", "..#"],
    "x": ["...", "...", "#.#", "#.#", ".#.", "#.#", "#.#"],
    "?": [".##.", "#..#", "...#", "..#.", "..#.", "....", "..#."],
    "!": ["#", "#", "#", "#", "#", ".", "#"],
    "=": ["....", "....", "####", "....", "####", "....", "...."],
    ">": ["...", "#..", "##.", "###", "##.", "#..", "..."],  # play arrow
    "v": [".......", ".......", "#######", ".#####.", "..###..", "...#...", "......."],
    " ": [".", ".", ".", ".", ".", ".", "."],
}
GLYPHS = {k: [r.ljust(len(v[0]), ".") for r in v] + ["." * len(v[0])] * (9 - len(v))
          for k, v in _RAW.items()}


def width(text, bold=False):
    w = sum(len(GLYPHS[c][0]) + 1 for c in text) - 1
    return w + (1 if bold else 0)


def pixels(text, x, y, bold=False):
    """Ink pixels for text with its top-left at (x, y)."""
    out = []
    for c in text:
        g = GLYPHS[c]
        for dy, row in enumerate(g):
            for dx, ch in enumerate(row):
                if ch == "#":
                    out.append((x + dx, y + dy))
                    if bold:
                        out.append((x + dx + 1, y + dy))
        x += len(g[0]) + 1 + (1 if bold else 0)
    return out


def draw(cv, text, x, y, colour="K", bold=False):
    cv.pixels(pixels(text, x, y, bold), colour)
